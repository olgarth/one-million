function esc(t) {
  return String(t == null ? '' : t).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; });
}
function ph(label) { return '<span class="ph">[' + esc(label) + ']</span>'; }
function val(v, label) { return v ? esc(v) : ph(label); }
function pd(s, v, label) { return (s.pd && v) ? esc(v) : ph(label); }
function cap(t) { return t ? t.charAt(0).toUpperCase() + t.slice(1) : t; }

function refMid(k) {
  var r = REFS[k];
  if (!r) return '';
  var P4M = { P4_main: 'абзац другий пункту 4 Постанови', P4_prop: 'абзац третій пункту 4 Постанови', P4_exc: 'абзац четвертий пункту 4 Постанови', P4_resp: 'абзац п\'ятий пункту 4 Постанови', P4_cat942: 'абзаци шостий - дев\'ятий пункту 4 Постанови' };
  if (P4M[k]) return P4M[k];
  if (k === 'D_intro' || k === 'D_groups' || k === 'D_resp') return 'вступна частина Доручення';
  if (k === 'D_1v') return 'підпункт «в» пункту 1 Доручення';
  if (k === 'D_1d') return 'підпункт «д» пункту 1 Доручення';
  var m = /^D_(\d)$/.exec(k); if (m) return 'пункт ' + m[1] + ' Доручення';
  m = /^R(\d+)$/.exec(k); if (m) return 'відповідь № ' + m[1] + ' Роз\'яснення';
  return r.f;
}
function refsText(list) {
  var seen = {}, out = [];
  (list || []).forEach(function (k) { var t = refMid(k); if (t && !seen[t]) { seen[t] = 1; out.push(t); } });
  return out.join('; ');
}
