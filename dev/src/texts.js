/* ===== Режим довідки: Додаток 1 ===== */
function respLine(kind, s) {
  var q = s.q;
  if (kind === 'crim') {
    if (!q.crim) return ph('не обліковано / обліковано у кількості ... випадків з підставами');
    if (q.crim === 'none' || q.crim === 'erdr' || q.crim === 'szch_simple') return 'не обліковано';
    if (q.crimWhen === 'outside') return 'не обліковано (у період з дня прийняття на службу до 13.02.2025)';
    var m = { verdict: 'обвинувальний вирок', suspicion: 'повідомлено про підозру', released401: 'звільнено від кримінальної відповідальності', rehab: 'провадження закрито з реабілітуючих підстав' }[q.crim];
    return 'обліковано у кількості 1 випадку (' + m + (q.crimDetails ? ': ' + esc(q.crimDetails) : ': ' + ph('підстави, реквізити')) + ')';
  }
  if (kind === 'disc' && (s.disc || []).length) {
    var da = discAnalysis(s), cr = da.rows.filter(function (x) { return x.counted; });
    if (!cr.length) return 'не обліковано';
    return 'обліковано у кількості ' + cr.length + ' ' + plural(cr.length, ['випадку', 'випадків', 'випадків']) + ' (' + esc(cr.map(function (x) { return x.label; }).join('; ')) + ')';
  }
  var n = parseInt(kind === 'adm' ? q.admCount : q.discCount, 10);
  if (isNaN(n)) return ph('не обліковано / обліковано у кількості ... випадків з підставами');
  if (!n) return 'не обліковано';
  var det = kind === 'adm' ? q.admDetails : q.discDetails;
  return 'обліковано у кількості ' + n + ' ' + plural(n, ['випадку', 'випадків', 'випадків']) + ' (' + (det ? esc(det) : ph('підстави, реквізити')) + ')';
}

