function phraseAgg(ids) {
  var agg = { yes: 0, no: 0, doubt: 0, list: [] };
  (ids || []).forEach(function (id) {
    var ph = PHRASE_INDEX[id];
    if (!ph) return;
    agg[ph.v]++;
    agg.list.push(ph);
  });
  return agg;
}

function ivMerge(list) {
  var a = list.filter(function (x) { return x && x[0] <= x[1]; }).map(function (x) { return [x[0], x[1]]; }).sort(function (p, q) { return p[0] - q[0]; });
  var out = [];
  a.forEach(function (x) {
    var l = out[out.length - 1];
    if (l && x[0] <= l[1] + 1) { if (x[1] > l[1]) l[1] = x[1]; }
    else out.push([x[0], x[1]]);
  });
  return out;
}
function ivLen(list) { return list.reduce(function (t, x) { return t + x[1] - x[0] + 1; }, 0); }
function ivSub(seg, cuts) {
  var res = [[seg[0], seg[1]]];
  ivMerge(cuts).forEach(function (c) {
    var next = [];
    res.forEach(function (x) {
      if (c[1] < x[0] || c[0] > x[1]) { next.push(x); return; }
      if (c[0] > x[0]) next.push([x[0], c[0] - 1]);
      if (c[1] < x[1]) next.push([c[1] + 1, x[1]]);
    });
    res = next;
  });
  return res;
}
function lowerBound(s) {
  var q = s.q || {};
  var war = dn(C.WAR), adm = dn(q.admDate);
  if (s.mode === 'cert') {
    var st = dn(q.svcStart);
    if (st !== null && st > war) return { d: st, why: 'adm' };
    return { d: war, why: 'war' };
  }
  if (q.path === 'strok_contract' || q.path === 'prewar_new' || q.path === 'prewar') return { d: war, why: 'war' };
  if (adm !== null) return { d: Math.max(adm, war), why: adm >= war ? 'adm' : 'war' };
  return { d: war, why: 'war' };
}

function computePeriods(s) {
  var cut = dn(C.CUTOFF);
  var lb = lowerBound(s);
  var res = [];
  (s.periods || []).forEach(function (p, idx) {
    var r = {
      id: p.id, n: idx + 1, p: p, from: p.from, to: p.to,
      rawDays: 0, days: 0, start: null, end: null, iv: [],
      status: 'count', reasons: [], needs: [], notes: [], refs: []
    };
    var f = dn(p.from), t = dn(p.to);
    if (f === null || t === null) {
      r.status = 'pending'; r.needs.push('не зазначено дати початку і закінчення періоду');
      res.push(r); return;
    }
    if (t < f) {
      r.status = 'pending'; r.needs.push('дата закінчення раніше за дату початку');
      res.push(r); return;
    }
    r.rawDays = t - f + 1;
    var start = f, end = t;
    if (start > cut) {
      r.status = 'exclude';
      r.reasons.push('період повністю після 13.02.2025: для права на Винагороду враховується участь станом на 13.02.2025');
      r.refs.push('P4_main', 'R5');
      res.push(r); return;
    }
    if (end > cut) {
      end = cut;
      r.notes.push('частину періоду після 13.02.2025 відсічено (' + (t - cut) + ' дн.)');
    }
    if (start < lb.d) {
      if (end < lb.d) { r.status = 'exclude'; r.reasons.push(lb.why === 'adm' ? 'період до дати прийняття (призову) на службу' : 'період до введення воєнного стану (24.02.2022)'); res.push(r); return; }
      r.notes.push((lb.why === 'adm' ? 'початок періоду раніше дати прийняття (призову) на службу' : 'початок періоду раніше 24.02.2022') + ', рахується з ' + fd(ds(lb.d)));
      start = lb.d;
    }
    r.start = start; r.end = end;
    /* перерви датами: віднімаються лише в межах врахованої частини періоду */
    var cuts = [], outside = 0, badBr = 0;
    (p.brk || []).forEach(function (b) {
      var bf = dn(b.from), bt = dn(b.to);
      if (bf === null || bt === null || bt < bf) { badBr++; return; }
      var cf = Math.max(bf, start), ct = Math.min(bt, end);
      if (cf > ct) { outside++; return; }
      cuts.push([cf, ct]);
    });
    r.iv = ivSub([start, end], cuts);
    r.days = ivLen(r.iv);
    var brDays = (end - start + 1) - r.days;
    if (brDays) r.notes.push('віднято ' + brDays + ' дн. перерв (відпустка, лікування, ВЛК, СЗЧ, вибуття з району)');
    if (outside) r.notes.push('перерви поза врахованою частиною періоду не впливають (' + outside + ')');
    if (badBr) { r.status = 'pending'; r.needs.push('перерву внесено без дат або з помилкою в датах'); }
    if (parseInt(p.breaks || 0, 10) > 0 && !(p.brk || []).length) { r.status = 'pending'; r.needs.push('вкажіть перерви датами (з ... по ...), щоб їх можна було правильно відняти'); }

    /* Джерело підтвердження */
    var src = s.mode === 'cert' ? 'combat' : (p.src || '');
    if (src === 'ubd' || src === '5718') {
      r.status = 'exclude'; r.docExcl = true;
      r.reasons.push(src === 'ubd'
        ? 'підтверджено лише довідкою за Додатком 6 до Порядку надання статусу УБД, яка не підтверджує безпосередню участь саме в районах ведення бойових дій'
        : 'підтверджено лише довідкою за Додатком 1 до доручення від 06.03.2023 № 5718/з, яка не підтверджує безпосередню участь саме в районах ведення бойових дій');
      r.refs.push('D_1v', 'R2', 'R6');
    } else if (src === 'other') {
      r.status = 'exclude'; r.docExcl = true;
      r.reasons.push('документ-підстава не належить до визначених дорученням № 5601/уд (наказ по стройовій частині, рапорт військовослужбовця, пояснення тощо)');
      r.refs.push('D_groups');
    } else if (!src) {
      r.status = 'pending'; r.needs.push('не обрано документ, яким підтверджено період');
    }

    var needGroups = src === 'combat';
    if (r.status === 'count' && needGroups) {
      var miss = [];
      if (!p.gA) miss.push('бойовий наказ (бойове розпорядження)');
      if (!p.gB) miss.push('ЖБД / журнал ведення оперативної обстановки / бойове донесення');
      if (!p.gC) miss.push('рапорт (донесення) командира про участь кожного військовослужбовця');
      if (miss.length) {
        r.status = 'pending';
        r.needs.push('бракує документа групи: ' + miss.join('; '));
        r.refs.push('D_groups');
      }
    }

    /* Район (місце) */
    if (p.place === 'community') {
      if (r.status === 'count') r.status = 'pending';
      r.needs.push('у документі зазначено лише територіальну громаду без населених пунктів (районів), потрібне уточнення');
      r.refs.push('R16');
    } else if (p.place === 'none') {
      if (r.status === 'count') r.status = 'pending';
      r.needs.push('не зазначено район (населені пункти) виконання завдань');
      r.refs.push('R16');
    }

    /* Характер завдання */
    if (p.task === 'outside') {
      r.status = 'exclude';
      r.reasons.push('завдання виконувалось поза районом ведення воєнних (бойових) дій (ППД, тил, навчання, відновлення боєздатності поза районом)');
      r.refs.push('P4_main', 'R19');
    } else if (p.task === 'support') {
      r.notes.push('забезпечувальні або спеціальні завдання в районі бойових дій (фортифікація, переправи, охорона, логістика, евакуація) враховуються, якщо виконувались у районі бойових дій');
      r.refs.push('R19', 'R20');
    } else if (p.task === 'doubt') {
      if (r.status === 'count') r.status = 'pending';
      r.needs.push('характер завдання не дозволяє однозначно віднести його до безпосередньої участі у бойових діях');
    } else if (!p.task) {
      if (r.status === 'count') r.status = 'pending';
      r.needs.push('не зазначено характер завдання');
    }

    /* Формулювання */
    var agg = phraseAgg(p.phrases);
    r.agg = agg;
    if (agg.no && !agg.yes) {
      if (r.status !== 'exclude') r.status = 'pending';
      r.needs.push('у документах відмічено формулювання, які не підтверджують безпосередню участь (' + agg.no + ')');
    } else if (agg.no && agg.yes) {
      if (r.status === 'count') r.status = 'pending';
      r.needs.push('відмічено суперечливі формулювання (є і такі, що підтверджують, і такі, що не підтверджують)');
    } else if (agg.doubt && !agg.yes) {
      if (r.status === 'count') r.status = 'pending';
      r.needs.push('відмічено лише двозначні формулювання (' + agg.doubt + ')');
    }

    /* Дефекти */
    (p.defects || []).forEach(function (id) {
      var d = DEFECT_INDEX[id];
      if (!d) return;
      if (d.e === 'reject') {
        if (r.status !== 'exclude') r.status = 'pending';
        r.needs.push('дефект документа: ' + d.t);
      } else if (d.e === 'clarify') {
        if (r.status === 'count') r.status = 'pending';
        r.needs.push('потребує уточнення: ' + d.t);
      } else {
        r.notes.push('зауваження: ' + d.t);
      }
    });

    /* Рішення комісії щодо періоду */
    if (p.decision === 'count' && r.status !== 'count') {
      r.overridden = true;
      r.overrideFrom = r.status;
      r.status = 'count';
      r.notes.push('враховано за рішенням комісії' + (p.note ? ': ' + p.note : ''));
    } else if (p.decision === 'exclude') {
      r.overridden = r.status !== 'exclude';
      r.status = 'exclude';
      r.reasons.push('не враховано за рішенням комісії' + (p.note ? ': ' + p.note : ''));
    }
    res.push(r);
  });
  return res;
}

function sumDays(list) {
  /* день рахується, якщо він входить до врахованої частини хоча б одного періоду і не є перервою саме в ньому */
  var all = [], plain = 0;
  list.forEach(function (r) { (r.iv || []).forEach(function (x) { all.push(x); }); plain += r.days || 0; });
  var u = ivMerge(all);
  var total = ivLen(u);
  return { days: total, overlap: Math.max(0, plain - total), iv: u };
}

