function dn(s) {
  if (!s) return null;
  var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s);
  if (!m) return null;
  return Math.round(Date.UTC(+m[1], +m[2] - 1, +m[3]) / 86400000);
}
function ds(n) {
  var d = new Date(n * 86400000);
  return d.getUTCFullYear() + '-' + String(d.getUTCMonth() + 1).padStart(2, '0') + '-' + String(d.getUTCDate()).padStart(2, '0');
}
function fd(s) {
  if (!s) return '___.___.______';
  var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s);
  return m ? m[3] + '.' + m[2] + '.' + m[1] : s;
}
function addYears(s, n) {
  var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s);
  if (!m) return null;
  var y = +m[1] + n, mo = +m[2], da = +m[3];
  if (mo === 2 && da === 29) { var leap = (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0; if (!leap) da = 28; }
  return y + '-' + String(mo).padStart(2, '0') + '-' + String(da).padStart(2, '0');
}
function fullYears(dob, at) {
  if (!dob || !at) return null;
  var a = /^(\d{4})-(\d{2})-(\d{2})$/.exec(dob), b = /^(\d{4})-(\d{2})-(\d{2})$/.exec(at);
  if (!a || !b) return null;
  var y = +b[1] - +a[1];
  if (+b[2] < +a[2] || (+b[2] === +a[2] && +b[3] < +a[3])) y--;
  return y;
}

