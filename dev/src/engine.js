function woundCertStatus(q) {
  if (q.wound === 'no') return 'hasnot';
  if (q.wound !== 'yes') return null;
  var wl = q.woundLink === 'zakhyst' ? 'vlk' : (q.woundLink === 'ne_zakhyst' ? 'other' : q.woundLink);
  if (wl === 'vlk' || wl === 'form5') return 'has';
  if (wl === 'other') return 'hasnot';
  return null;
}
function evaluateCert(s) {
  var periods = computePeriods(s);
  var counted = periods.filter(function (r) { return r.status === 'count'; });
  var pending = periods.filter(function (r) { return r.status === 'pending'; });
  var sum = sumDays(counted);
  var q = s.q || {};
  var gaps = [];
  if (!periods.length) gaps.push('не внесено жодного періоду');
  pending.forEach(function (r) { gaps.push('період № ' + r.n + ': ' + r.needs.join('; ')); });
  if (!q.crim) gaps.push('розділ 2: відомості про кримінальну відповідальність');
  if (q.admCount === undefined || q.admCount === '') gaps.push('розділ 2: адміністративна відповідальність (0, якщо немає)');
  if ((q.discCount === undefined || q.discCount === '') && !(s.disc || []).length) gaps.push('розділ 2: дисциплінарні стягнення (0, якщо немає)');
  if (CRIM_CASES.indexOf(q.crim) >= 0 && !q.crimWhen) gaps.push('розділ 2: коли повідомлено про підозру (настала подія)');
  if (!q.wound) gaps.push('розділ 3.1: поранення (має / не має)');
  else if (q.wound === 'yes' && !woundCertStatus(q)) gaps.push('розділ 3.1: документ, що підтверджує зв\'язок поранення (захворювання) із захистом Батьківщини');
  if (!q.captive) gaps.push('розділ 3.2: полон (перебував / не перебував)');
  return { periods: periods, counted: counted, pending: pending, days: sum.days, overlap: sum.overlap, iv: sum.iv, gaps: gaps, ready: !gaps.length };
}

